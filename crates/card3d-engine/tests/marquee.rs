//! The marquee's maths against the TypeScript (packages/core/src/marquee/: constants.ts, pose.ts,
//! strip.ts): the hash and easings, slot randoms, per-card jitter, the responsive layout, slot poses
//! (steady, pinned with a turn, and the intro fly-in at three moments, for two aspects),
//! slot assignment, the seek distance, and the strip's motion store through a scripted sequence of
//! drift, gate, gesture, scrub, fling, wheel, seek, focus-hold and preview steps.
//!
//! How the numbers were made: a Node 24 script (kept outside the repository, in the session
//! scratchpad `marquee/dump.ts`) ran the TypeScript modules themselves and printed these tables.
//! Everything agrees to 1e-12 (relative) apart from the raw hash (see `close_hash`).

#![allow(clippy::type_complexity, reason = "tables of recorded cases, one tuple per row")]

use card3d_engine::marquee_model::*;

fn close(a: f64, b: f64, what: &str) {
    assert!((a - b).abs() <= 1e-12 * b.abs().max(1.0), "{what}: {a} vs {b}");
}

/// The hash multiplies `sin` by 43758: a last-bit difference between V8's `sin` and the `libm`
/// crate's (it happens, e.g. at 25.98) shows as a few 1e-12.
fn close_hash(a: f64, b: f64, what: &str) {
    assert!((a - b).abs() <= 1e-10, "{what}: {a} vs {b}");
}

#[test]
fn hash_easings_constants() {
    for &(x, v) in HASH {
        close_hash(hash(x), v, &format!("hash({x})"));
    }
    for &(x, v) in SEEK_EASE {
        close(seek_ease(x), v, &format!("seekEase({x})"));
    }
    for &(x, v) in EASE_IN_OUT {
        close(ease_in_out_cubic(x), v, &format!("easeInOutCubic({x})"));
    }
    close(viewport_h(), CONSTS.0, "VIEWPORT_H");
    close(cos_half(), CONSTS.1, "COS_HALF");
    close(PERSP, CONSTS.2, "PERSP");
}

#[test]
fn randoms_and_jitter() {
    for (e, r) in SLOT_RANDOMS.iter().enumerate() {
        let s = slot_randoms(e);
        for (k, (a, b)) in [s.phase_pitch, s.pitch_bias, s.intro_jitter, s.intro_side].iter().zip(r).enumerate() {
            close(*a, *b, &format!("slotRandoms({e})[{k}]"));
        }
    }
    for &(o, j) in JITTER {
        let s = logical_jitter(o);
        for (k, (a, b)) in [s.yaw, s.pitch, s.roll, s.phase].iter().zip(j).enumerate() {
            close(*a, b, &format!("logicalJitter({o})[{k}]"));
        }
    }
}

#[test]
fn layouts() {
    for &((w, h, band, paused), l) in LAYOUTS {
        let got = compute_layout(w, h, band, paused);
        for (k, (a, b)) in [got.row_y_frac, got.x_frac, got.center_height_frac, got.card_spacing].iter().zip(l).enumerate() {
            close(*a, b, &format!("layout {w}×{h} [{k}]"));
        }
        assert!(layout_valid(&got));
    }
    let f = frame_inputs(&compute_layout(1200.0, 750.0, None, false), 1.6);
    for (k, (a, b)) in [f.viewport_w, f.w, f.x_off, f.y_row, f.spacing].iter().zip(FRAME).enumerate() {
        close(*a, b, &format!("frameInputs[{k}]"));
    }
    assert!(layout_differs(&DEFAULT_LAYOUT, &compute_layout(390.0, 844.0, None, false)));
    assert!(!layout_differs(&DEFAULT_LAYOUT, &DEFAULT_LAYOUT));
}

#[test]
fn poses() {
    let layout = compute_layout(1200.0, 750.0, None, false);
    for &(aspect, a, e, t, variant, logical, want, visible) in POSES {
        let turn = if variant == 2 { TurnPose { yaw: 0.4, pitch: -0.3, flip: std::f64::consts::PI, stand: 0.0 } } else { TurnPose::default() };
        let intro = match variant {
            3 => Some(0.05),
            4 => Some(0.4),
            5 => Some(0.8),
            _ => None,
        };
        let p = slot_pose(&PoseInput {
            a,
            t,
            frame: frame_inputs(&layout, aspect),
            slot: slot_randoms(e),
            jitter: logical_jitter(logical as f64),
            turn,
            preview_paused: variant == 2,
            intro,
        });
        let what = format!("pose aspect {aspect} a {a} e {e} t {t} variant {variant}");
        assert_eq!(p.visible, visible, "{what}: visible");
        for (k, (x, y)) in [p.x, p.y, p.z, p.pitch, p.yaw, p.roll, p.scale].iter().zip(want).enumerate() {
            close(*x, y, &format!("{what} [{k}]"));
        }
    }
    for &(t, done, g) in INTRO_GATE {
        close(intro_gate(t, done), g, "introGate");
    }
}

