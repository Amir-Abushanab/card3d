const EPS: f64 = 1e-9;

type LogoCase = (&'static str, &'static str, Option<f64>, f64, bool, [f64; 4]);
type TextCase = (&'static str, &'static str, &'static str, f64, &'static [[f64; 4]]);

fn close(name: &str, got: &[f64], want: &[f64]) {
    assert_eq!(got.len(), want.len(), "{name}: length");
    for (i, (g, w)) in got.iter().zip(want).enumerate() {
        let ok = (g.is_nan() && w.is_nan()) || (g - w).abs() <= EPS;
        assert!(ok, "{name}[{i}]: got {g}, want {w}");
    }
}

fn flat_layout(l: &BrandingLayout) -> Vec<f64> {
    let n = l.number_line;
    vec![
        l.e,
        l.m,
        l.t,
        l.i,
        l.logo.width,
        l.logo.height,
        l.logo.left,
        l.logo.top,
        l.text_bottom,
        l.z,
        l.name_left.unwrap_or(f64::NAN),
        l.text_right.unwrap_or(f64::NAN),
        l.corner_top.unwrap_or(f64::NAN),
        n.map_or(f64::NAN, |n| n.left),
        n.map_or(f64::NAN, |n| n.right),
        n.map_or(f64::NAN, |n| n.y),
        n.map_or(f64::NAN, |n| n.h),
    ]
}

fn rect(r: Rect) -> [f64; 4] {
    [r.x, r.y, r.w, r.h]
}

fn flat_frame(x: &CardFrame) -> Vec<f64> {
    vec![x.width, x.height, x.body_width, x.body_height, x.corner_radius, x.chip.x, x.chip.y, x.chip.rotation, x.chip.width, x.chip.height, x.chip.top]
}

fn frame(kind: &str) -> Option<CardFrame> {
    let r = ID1_CORNER * BODY_SCALE;
    match kind {
        "land" => Some(iso_frame(false, r, &[])),
        "port" => Some(iso_frame(true, r, &[])),
        _ => None,
    }
}

fn layout_for(name: &str) -> BrandingLayout {
    let (kind, ov, depth) = match name {
        "default_land" => ("land", FrontLayoutOverride::default(), 0.02),
        "default_port" => ("port", FrontLayoutOverride::default(), 0.02),
        "default_none" => ("none", FrontLayoutOverride::default(), 0.02),
        "over_land" | "over_port" | "over_none" => (
            &name[5..],
            FrontLayoutOverride { logo_left: Some(0.1), logo_top: Some(0.12), name_bottom: Some(0.2), name_font_height: Some(0.06), ..Default::default() },
            0.02,
        ),
        "big_land" => ("land", FrontLayoutOverride { logo_left: Some(0.9), name_bottom: Some(0.01), logo_top: Some(0.01), ..Default::default() }, 0.02),
        _ => panic!("{name}"),
    };
    branding_layout(&ov, depth, frame(kind).as_ref())
}

