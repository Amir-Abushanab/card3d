#!/usr/bin/env node
/**
 * Regenerates the "Rust crates" section of THIRD_PARTY_NOTICES.md: every third-party crate compiled
 * into a build we distribute, with its licence text and copyright lines, from the crates' own sources
 * in Cargo's registry (~/.cargo/registry/src). The section sits between the BEGIN / END markers; the
 * rest of the file is hand-written.
 *
 *   node scripts/third-party-rust.mjs           # rewrite the section
 *   node scripts/third-party-rust.mjs --check   # fail if it is stale (Cargo.lock or a feature changed)
 *
 * The builds (BUILDS below) are the ones the packaging scripts make: the two web builds
 * (crates/card3d-web/build-web.sh), the Apple static library (apple/build-xcframework.sh) and the
 * Android shared library (android/build.sh). A build's crates are its `cargo tree` with normal
 * dependencies only, for its targets and features: build scripts and procedural macros run at build
 * time and nothing of them is distributed, so they and their dependencies are left out, as are dev
 * dependencies. Runs offline (`--offline --locked`): the crates must have been fetched (`cargo fetch`,
 * or any build).
 *
 * Licence choice: a crate offering several licences is listed under the first of PREFERENCE that it
 * ships a text for (MIT before everything else); a crate requiring several (`A AND B`) is listed under
 * each. Crates whose package has no licence file get theirs from OVERRIDES (copied from the upstream
 * repository). Identical licence texts are printed once, after the list of crates they cover.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const NOTICES = join(root, "THIRD_PARTY_NOTICES.md");
const BEGIN = "<!-- BEGIN rust-crates: generated by scripts/third-party-rust.mjs from Cargo.lock; do not edit by hand -->";
const END = "<!-- END rust-crates -->";
const CHECK = process.argv.includes("--check");

