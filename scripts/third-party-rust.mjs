const cargo = (args) => {
  try {
    return execFileSync("cargo", [...args, "--offline", "--locked"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 << 20 });
  } catch (e) {
    // `pnpm check` on a machine without Rust (the JavaScript-only setup): nothing to compare against.
    if (e.code === "ENOENT" && CHECK) {
      console.warn("⚠ Rust crate notices not checked: cargo is not installed");
      process.exit(0);
    }
    console.error(String(e.stderr || e.message).trim());
    console.error("\nthird-party-rust: cargo failed; the crates must be fetched first (`cargo fetch`).");
    process.exit(2);
  }
};

/** name@version → { build ids } */
function inventory() {
  const crates = new Map();
  for (const b of BUILDS)
    for (const run of b.runs) {
      const out = cargo(["tree", "-e", "normal,no-proc-macro", "--prefix", "none", "--format", "{p}", ...run]);
      for (const line of out.split("\n")) {
        const m = /^(\S+) v(\S+)(?: \((.*)\))?/.exec(line.trim());
        if (!m || (m[3] && !m[3].startsWith("*") && m[3] !== "*")) continue; // path (workspace) crates
        const key = `${m[1]}@${m[2]}`;
        if (!crates.has(key)) crates.set(key, new Set());
        crates.get(key).add(b.id);
      }
    }
  return crates;
}

/** `A OR (B AND C)` → [[A], [B, C]] (disjunctive normal form; `WITH` exceptions stay attached). */
function parseSpdx(expr) {
  const tokens = expr
    .replace(/\//g, " OR ")
    .replace(/([()])/g, " $1 ")
    .trim()
    .split(/\s+/);
  let i = 0;
  const primary = () => {
    if (tokens[i] === "(") {
      i++;
      const v = or();
      i++; // ")"
      return v;
    }
    let id = tokens[i++];
    if (tokens[i] === "WITH") {
      id += ` WITH ${tokens[i + 1]}`;
      i += 2;
    }
    return [[id]];
  };
  const and = () => {
    let v = primary();
    while (tokens[i] === "AND") {
      i++;
      const w = primary();
      v = v.flatMap((a) => w.map((b) => [...a, ...b]));
    }
    return v;
  };
  const or = () => {
    let v = and();
    while (tokens[i] === "OR") {
      i++;
      v.push(...and());
    }
    return v;
  };
  return or();
}

function classify(text) {
  if (/UNICODE LICENSE V3/i.test(text)) return "Unicode-3.0";
  if (/Permission is hereby granted, free of charge/i.test(text)) return "MIT";
  if (/Apache License\s+Version 2\.0/i.test(text) && /TERMS AND CONDITIONS/.test(text)) return "Apache-2.0";
  if (/provided ['‘]as-is['’]/i.test(text) && /plainly marked/i.test(text)) return "Zlib";
  if (/Redistribution and use in source and binary forms/i.test(text))
    return /Neither the name|names of (its|the) contributors/i.test(text) ? "BSD-3-Clause" : "BSD-2-Clause";
  if (/Permission to use, copy, modify, and\/or distribute this software for any\s+purpose/i.test(text))
    return /provided that the above\s+copyright notice/i.test(text) ? "ISC" : "0BSD";
  if (/This is free and unencumbered software/i.test(text)) return "Unlicense";
  return null;
}

/** Where a licence's own wording starts: copyright lines are taken from the text before it only. */
const BODY_START =
  /^\s*(Permission is hereby granted|Permission to use, copy|Redistribution and use|This software is provided|Apache License|NOTICE TO USER|This is free and unencumbered)/i;
const COPYRIGHT_LINE = /^\s*(copyright\b|\(c\)|©)/i;
const TEMPLATE = /\[yyyy\]|\{yyyy\}|\[name of copyright owner\]|COPYRIGHT AND PERMISSION NOTICE/i;

/** Copyright statements anywhere in a text: "Copyright" or "©" followed by a year. */
const statements = (text) =>
  text
    .split(/\r?\n/)
    .filter((l) => /^\s*(copyright\s*(\(c\)|©)?|\(c\)|©)\s*\d{4}/i.test(l) && !TEMPLATE.test(l))
    .map((l) => l.trim());

/** → { copyright: [lines], body } for one licence file. */
function split(text) {
  const lines = text.replace(/\r\n?/g, "\n").replace(/\t/g, "    ").split("\n");
  const start = lines.findIndex((l) => BODY_START.test(l));
  const head = start < 0 ? [] : lines.slice(0, start);
  const copyright = [];
  const rest = [];
  for (const [i, l] of head.entries()) {
    if (COPYRIGHT_LINE.test(l) && !TEMPLATE.test(l)) copyright.push(l.trim());
    else if (/^\s*all rights reserved\.?\s*$/i.test(l) && copyright.length && COPYRIGHT_LINE.test(head[i - 1] ?? ""))
      copyright[copyright.length - 1] += " All rights reserved.";
    else if (!/^\s*(the )?mit license( \(mit\))?\s*$/i.test(l) && !/^\s*#\s*license\s*$/i.test(l)) rest.push(l);
  }
  const bodyLines = [...rest, ...(start < 0 ? lines : lines.slice(start))];
  let body = bodyLines
    .join("\n")
    .replace(/^\s*\n/, "")
    .replace(/\s+$/, "");
  // The Apache licence alone: its terms only (the appendix explains how to apply it to one's own work).
  const end = body.indexOf("END OF TERMS AND CONDITIONS");
  if (/^\s*Apache License/.test(body) && end >= 0) body = body.slice(0, end + "END OF TERMS AND CONDITIONS".length);
  return { copyright, body: dedent(body).replace(/\n{3,}/g, "\n\n") };
}

const dedent = (s) => {
  const lines = s.split("\n");
  const n = Math.min(...lines.filter((l) => l.trim()).map((l) => /^ */.exec(l)[0].length));
  return lines
    .map((l) => l.slice(n))
    .join("\n")
    .replace(/[ \t]+$/gm, "");
};
const normalize = (body) => body.replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/\s+/g, " ").trim().toLowerCase();

const LICENSE_FILE = /^(licen[cs]e|copying|copyright|notice|unlicense)/i;
function licenseFiles(dir) {
  const files = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (/^licen[cs]es?$/i.test(name)) for (const f of readdirSync(p).sort()) files.push({ name: `${name}/${f}`, text: readFileSync(join(p, f), "utf8") });
    } else if (LICENSE_FILE.test(name)) files.push({ name, text: readFileSync(p, "utf8") });
  }
  return files.map((f) => ({ ...f, license: /^notice/i.test(f.name) ? "NOTICE" : classify(f.text) }));
}

/** One crate → [{ license, copyright, body, notice? }] (one per licence it is used under). */
function resolveCrate(pkg) {
  const override = OVERRIDES[pkg.name];
  const files = licenseFiles(dirname(pkg.manifest_path));
  if (!pkg.license) throw new Error(`${pkg.name} ${pkg.version}: no SPDX licence in Cargo.toml (license-file: ${pkg.license_file ?? "none"})`);
  const options = parseSpdx(pkg.license);
  const has = (id) => files.some((f) => f.license === id);
  const rank = (opt) => Math.max(...opt.map((id) => (PREFERENCE.includes(id) ? PREFERENCE.indexOf(id) : 99)));
  const sorted = [...options].sort((a, b) => rank(a) - rank(b));
  if (override) {
    const opt = sorted.find((o) => o.length === 1 && o[0] === override.license);
    if (!opt) throw new Error(`${pkg.name}: override ${override.license} is not one of ${pkg.license}`);
    return [{ license: override.license, copyright: override.copyright, body: null, from: override.from }];
  }
  const chosen = sorted.find((o) => o.every(has));
  if (!chosen)
    throw new Error(
      `${pkg.name} ${pkg.version}: ships no text for any of ${pkg.license} (files: ${files.map((f) => `${f.name}=${f.license}`).join(", ") || "none"}); add an OVERRIDES entry`,
    );
  for (const id of chosen) if (!PREFERENCE.includes(id)) throw new Error(`${pkg.name}: unexpected licence ${id}`);
  const notice = files
    .filter((f) => f.license === "NOTICE")
    .map((f) => f.text.trim())
    .join("\n\n");
  return chosen.map((id) => {
    const mine = files.filter((f) => f.license === id).sort((a, b) => specificity(b.name, id) - specificity(a.name, id));
    const parts = mine.map((f) => split(f.text));
    let copyright = [...new Set(parts.flatMap((p) => p.copyright))];
    // Many crates' MIT text has no copyright line; their other licence files (a COPYRIGHT file, a
    // filled-in Apache appendix) may name the holder.
    if (!copyright.length) copyright = [...new Set(files.filter((f) => f.license !== id).flatMap((f) => statements(f.text)))];
    return { license: id, copyright, body: parts[0].body, notice: id === "Apache-2.0" && notice ? notice : undefined };
  });
}
/** LICENSE-MIT over LICENSE for MIT, etc. */
const specificity = (name, id) => (name.toUpperCase().includes(id.split("-")[0].toUpperCase()) ? 1 : 0);

/** Authors without e-mail addresses, for crates whose licence text has no copyright line. */
const authors = (pkg) => (pkg.authors ?? []).map((a) => a.replace(/\s*<[^>]*>/, "").trim()).filter(Boolean);

function generate(handWritten) {
  const meta = JSON.parse(cargo(["metadata", "--format-version", "1", "--all-features"]));
  const byKey = new Map(meta.packages.map((p) => [`${p.name}@${p.version}`, p]));
  const crates = inventory();
  const counts = Object.fromEntries(BUILDS.map((b) => [b.id, 0]));
  for (const builds of crates.values()) for (const b of builds) counts[b]++;

  // license → normalized body → { body, entries }
  const groups = new Map();
  const pending = [];
  for (const [key, builds] of [...crates].sort(([a], [b]) => a.localeCompare(b))) {
    const pkg = byKey.get(key);
    if (!pkg) throw new Error(`${key}: not in cargo metadata`);
    for (const r of resolveCrate(pkg)) {
      const entry = { pkg, builds, ...r };
      if (r.body == null) pending.push(entry);
      else add(groups, r.license, r.body, entry);
    }
  }
  pending.push({ pkg: { name: STD.name }, builds: new Set(BUILDS.map((b) => b.id)), license: STD.license, copyright: STD.copyright, note: STD.note });
  // Overrides and the standard library take the licence's most common text.
  for (const e of pending) {
    const g = [...(groups.get(e.license)?.values() ?? [])].sort((a, b) => b.entries.length - a.entries.length)[0];
    if (!g) throw new Error(`${e.pkg.name}: no ${e.license} text among the crates to use`);
    g.entries.push(e);
  }

  const order = Object.keys(TITLES);
  const out = [];
  const p = (...l) => out.push(...l);
  const buildList = (s) =>
    BUILDS.filter((b) => s.has(b.id))
      .map((b) => b.id)
      .join(", ");
  p(BEGIN, "", "## Rust crates", "");
  p(
    "The card engine is compiled together with the Rust standard library and the crates below. Builds: " +
      BUILDS.map((b) => `**${b.id}**, ${b.what}`).join("; ") +
      ". The web builds ship in `@card3d/core` (`wasm/`) and `@card3d/element` (`dist/standalone/engine/`).",
    "",
    "| build | third-party crates |",
    "| --- | --- |",
    ...BUILDS.map((b) => `| ${b.id} | ${counts[b.id]} |`),
    "",
    `Each web build's JavaScript glue (\`card3d_web.js\`) is generated by wasm-bindgen-cli ${toolVersion("wasm-bindgen-cli")} and its chunk loader ` +
      `(\`__wasm_split.*.js\`) by wasm_split_cli_support ${toolVersion("wasm_split_cli_support")}, from the projects listed here as \`wasm-bindgen\` and ` +
      "`wasm_split_helpers` (same licences and authors).",
    "",
    "Build scripts and procedural macros run only at build time and are not listed. A crate offering a choice of licences is listed under the " +
      "first of " +
      PREFERENCE.slice(0, 6).join(", ") +
      " that it ships a text for; one requiring two is listed under both. Each licence text is printed once, after the crates it covers, " +
      "with their copyright lines in the list.",
    "",
  );
  const apacheAbove = /Apache License\s+Version 2\.0, January 2004/.test(handWritten) && handWritten.includes("END OF TERMS AND CONDITIONS");
  for (const lic of order) {
    const variants = [...(groups.get(lic)?.values() ?? [])].sort((a, b) => b.entries.length - a.entries.length || a.first.localeCompare(b.first));
    variants.forEach((g, i) => {
      p(`### ${TITLES[lic]}${variants.length > 1 ? ` (${i + 1} of ${variants.length})` : ""}`, "");
      for (const e of g.entries.sort((a, b) => a.pkg.name.localeCompare(b.pkg.name) || String(a.pkg.version).localeCompare(String(b.pkg.version)))) {
        const name = e.pkg.version ? `\`${e.pkg.name}\` ${e.pkg.version}` : e.pkg.name;
        let who = e.copyright.join(" ");
        if (!who) {
          if (g.entries.length === 1 && statements(g.body).length) who = "copyright notices in the text below";
          else {
            const a = authors(e.pkg);
            who = `the ${e.pkg.name} authors${a.length ? ` (${a.join(", ")})` : ""}`;
          }
        }
        const extra = [e.note, e.from ? `licence from ${e.from}; the package has none` : null, e.notice ? "NOTICE below" : null].filter(Boolean);
        p(`- ${name} (${buildList(e.builds)}): ${who}${extra.length ? ` [${extra.join("; ")}]` : ""}`);
      }
      p("");
      if (lic === "Apache-2.0" && apacheAbove) p("The Apache License 2.0 text is printed in full under Paper Shaders, above.", "");
      else p("```", g.body, "```", "");
      for (const e of g.entries.filter((x) => x.notice)) p(`\`${e.pkg.name}\`'s NOTICE:`, "", "```", e.notice, "```", "");
    });
  }
  for (const lic of groups.keys()) if (!order.includes(lic)) throw new Error(`no title for ${lic}`);
  p(END);
  return { text: out.join("\n"), counts, total: crates.size, licences: [...groups.keys()] };
}

function add(groups, license, body, entry) {
  if (!groups.has(license)) groups.set(license, new Map());
  const k = normalize(body);
  const m = groups.get(license);
  if (!m.has(k)) m.set(k, { body, entries: [], first: entry.pkg.name });
  m.get(k).entries.push(entry);
}

/** The tool versions build-web.sh installs (`cargo install <tool> --version X`). */
function toolVersion(tool) {
  const sh = readFileSync(join(root, "crates/card3d-web/build-web.sh"), "utf8");
  const m = new RegExp(`cargo install ${tool}\\s+--version\\s+([\\d.]+)`).exec(sh);
  if (!m) throw new Error(`build-web.sh: no \`cargo install ${tool} --version\``);
  return m[1];
}

// ---------------------------------------------------------------------------------------------------

const file = readFileSync(NOTICES, "utf8");
const a = file.indexOf(BEGIN);
const b = file.indexOf(END);
if (a < 0 || b < a) {
  console.error(`third-party-rust: ${NOTICES} has no generated section (the BEGIN / END markers)`);
  process.exit(1);
}
const handWritten = file.slice(0, a) + file.slice(b + END.length);
const { text, counts, total, licences } = generate(handWritten);
const next = file.slice(0, a) + text + file.slice(b + END.length);
const summary = `${total} crates (${Object.entries(counts)
  .map(([k, v]) => `${k} ${v}`)
  .join(", ")}); licences: ${licences.join(", ")}`;
if (CHECK) {
  if (next !== file) {
    console.error(`✗ THIRD_PARTY_NOTICES.md: the Rust crates section is stale (${summary}). Run: pnpm notices`);
    process.exit(1);
  }
  console.log(`✓ Rust crate notices up to date: ${summary}`);
} else {
  if (next !== file) writeFileSync(NOTICES, next);
  console.log(`${next !== file ? "updated" : "unchanged"} THIRD_PARTY_NOTICES.md: ${summary}`);
}
