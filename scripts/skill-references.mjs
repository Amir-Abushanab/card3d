#!/usr/bin/env node
/**
 * Writes the generated references of the agent skills the packages ship (packages/<pkg>/skills/,
 * TanStack Intent): the design model's field tables, presets, face shaders, effects, examples and the
 * custom-shader contract, all from `designSpaceSections()` (@card3d/core/describe), the text generated
 * from the engine's own catalogs that Card Studio's describe-a-finish uses. So the skills can't drift
 * from the code: `pnpm check` fails when a reference is stale.
 *
 *   node scripts/skill-references.mjs           # rewrite the references
 *   node scripts/skill-references.mjs --check   # fail if one is stale
 *
 * Runs the TypeScript sources directly (Node's type stripping, as the other .ts tools here); no build.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const CHECK = process.argv.includes("--check");
const { designSpaceSections } = await import(join(root, "packages/core/src/describe.ts"));

const sections = new Map(designSpaceSections().map((s) => [s.id, s]));
const section = (id) => {
  const s = sections.get(id);
  if (!s) throw new Error(`designSpaceSections() has no section "${id}"`);
  return `## ${s.title}\n\n${s.body.trim()}\n`;
};

const HEADER = (title, ids) =>
  [
    `<!-- Generated by scripts/skill-references.mjs from designSpaceSections() in @card3d/core/describe (sections: ${ids.join(", ")}). Do not edit: run \`pnpm skills:refs\`. -->`,
    "",
    `# ${title}`,
    "",
    'Generated from the engine\'s own catalogs, the same text Card Studio\'s describe-a-finish reads. Field lines read `` `key` (type or range): what it does ``; "— leave out" marks fields a design written from a description shouldn\'t set (uploads, licensed assets, internal state). A host that has its own images may still set them (`decals`, `surfaceSources`, `logo.src`). Section names in quotes ("Lighting", "Fonts") refer to headings in these references.',
    "",
  ].join("\n");

const CORE = join(root, "packages/core/skills");
const FILES = [
  {
    path: join(CORE, "card-design-json/references/design-fields.md"),
    title: "Design model reference",
    ids: ["fields", "recipe", "body", "stage"],
  },
  { path: join(CORE, "card-design-json/references/presets.md"), title: "Presets", ids: ["presets"] },
  {
    path: join(CORE, "card-design-json/references/shaders-and-effects.md"),
    title: "Face shaders and add-ons",
    ids: ["shaders", "addons"],
  },
  { path: join(CORE, "card-design-json/references/examples.md"), title: "Example designs", ids: ["examples"] },
  {
    path: join(CORE, "custom-face-shaders-wgsl/references/prelude.md"),
    title: "Custom WGSL face shaders: contract and prelude",
    ids: ["custom"],
  },
];

let stale = 0;
for (const f of FILES) {
  const text = `${HEADER(f.title, f.ids)}\n${f.ids.map(section).join("\n")}`;
  const rel = relative(root, f.path);
  if (CHECK) {
    if (!existsSync(f.path) || readFileSync(f.path, "utf8") !== text) {
      console.error(`✗ ${rel} is stale: run pnpm skills:refs`);
      stale++;
    }
    continue;
  }
  mkdirSync(dirname(f.path), { recursive: true });
  writeFileSync(f.path, text);
  console.log(`wrote ${rel} (${text.split("\n").length} lines)`);
}
if (stale) process.exit(1);
if (CHECK) console.log(`✓ skill references are current (${FILES.length} files)`);
